// Run: xvfb-run -a node_modules/.bin/electron --no-sandbox --ozone-platform=x11 electron/browser-control.integration.cjs
const {app,BrowserWindow,webContents}=require('electron')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const os=require('node:os')
const http=require('node:http')
const {setTimeout:delay}=require('node:timers/promises')
const {createController}=require('./browser-control')
app.disableHardwareAcceleration()
app.whenReady().then(async()=>{
  const directory=fs.mkdtempSync(path.join(os.tmpdir(),'libro-browser-integration-'))
  const server=http.createServer((req,res)=>{
    if(req.url==='/missing') {res.writeHead(404).end('missing');return}
    if(req.url==='/failed') {req.socket.destroy();return}
    if(req.url==='/download' || req.url==='/slow-download') {
      res.writeHead(200,{'Content-Type':'application/octet-stream','Content-Disposition':'attachment; filename="fixture.txt"','Content-Length':req.url==='/download'?5:100000})
      res.write(req.url==='/download'?'hello':Buffer.alloc(4096,65))
      if(req.url==='/download')res.end()
      return
    }
    res.writeHead(200,{'Content-Type':'text/html'}).end('<!doctype html><style>body{margin:0;background:white;min-height:2200px}input#name{position:absolute;left:30px;top:40px;width:200px;height:35px}button#click{position:absolute;left:30px;top:100px}section{position:absolute;top:200px}#bottom{position:absolute;top:2000px}</style><label for="name">Name</label><input id="name"><button id="click" onclick="document.body.dataset.clicked=Number(document.body.dataset.clicked||0)+1">Click</button><dialog><input></dialog><section><label for="choice">Choice</label><select id="choice"><option value="a">Alpha</option><option value="b">Beta</option></select><label><input id="checked" type="checkbox">Agree</label><input id="upload" type="file"><div id="shadow"></div></section><button id="bottom">Bottom button</button><script>document.querySelector("#shadow").attachShadow({mode:"open"}).innerHTML="<button id=shadow-button>Shadow button</button>"</script>')
  })
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve))
  const origin=`http://127.0.0.1:${server.address().port}`
  const win=new BrowserWindow({width:640,height:520,webPreferences:{webviewTag:true}})
  try {
    const page=origin

    await win.loadURL('data:text/html,'+encodeURIComponent('<div id="frame-panel"><webview data-sid="test" style="width:500px;height:400px"></webview></div>'))
    await win.webContents.executeJavaScript(`new Promise(resolve=>{const wv=document.querySelector('webview');window.__libroWebviews={panel:wv};wv.addEventListener('dom-ready',resolve,{once:true});wv.src=${JSON.stringify(page)}})`)
    const id=await win.webContents.executeJavaScript("document.querySelector('webview').getWebContentsId()")
    const target=webContents.fromId(id)
    const control=createController(()=>win,id=>webContents.fromId(id),{downloadDir:directory})
    assert.equal((await control({action:'list'}))[0].id,'panel')
    await win.webContents.executeJavaScript(`window.libroWorkspace={select:id=>{document.getElementById('frame-'+id).style.display='block'}};document.getElementById('frame-panel').style.display='none'`)
    await assert.rejects(control({action:'screenshot',panel:'panel'}),/Show the browser/)
    await control({action:'select_panel',panel:'panel'})
    assert.equal((await control({action:'list'}))[0].visible,true)
    for(const zoom of [1,1.5]) {
      target.setZoomFactor(zoom)
      await target.executeJavaScript("document.querySelector('input').value=''")
      await control({action:'click',panel:'panel',x:60,y:55})
      await control({action:'text',panel:'panel',text:'Hello'})
      assert.equal(await target.executeJavaScript("document.querySelector('input').value"),'Hello')
      await control({action:'click',panel:'panel',x:55,y:110})
      assert.equal(await target.executeJavaScript("document.body.dataset.clicked"),zoom===1?'1':'2')
      const shot=await control({action:'screenshot',panel:'panel'})
      const viewport=await target.executeJavaScript('({width:innerWidth,height:innerHeight})')
      assert.equal(shot.width,viewport.width)
      assert.equal(shot.height,viewport.height)
      assert.ok(Buffer.from(shot.data,'base64').length>100)
      if(zoom===1) fs.writeFileSync('/tmp/libro-agent-cursor.png',Buffer.from(shot.data,'base64'))
      const cursor=await target.executeJavaScriptInIsolatedWorld(998,[{code:'({open:libroAgentCursor.matches(":popover-open"),pointer:getComputedStyle(libroAgentCursor).pointerEvents,x:libroAgentCursor.getBoundingClientRect().x})'}])
      assert.deepEqual(cursor,{open:true,pointer:'none',x:55})
    }
    const edge = await target.executeJavaScript('({x:innerWidth-1,y:innerHeight-1})')
    await control({action:'move',panel:'panel',...edge})
    assert.equal(await target.executeJavaScriptInIsolatedWorld(998,[{code:'(() => { const r=libroAgentCursorLabel.getBoundingClientRect();return r.x>=0 && r.y>=0 && r.right<=innerWidth && r.bottom<=innerHeight })()'}]),true)
    fs.writeFileSync('/tmp/libro-agent-cursor-edge.png',Buffer.from((await control({action:'screenshot',panel:'panel'})).data,'base64'))
    await target.executeJavaScript("document.querySelector('dialog').showModal()")
    await control({action:'move',panel:'panel',x:60,y:60})
    assert.equal(await target.executeJavaScriptInIsolatedWorld(998,[{code:'libroAgentCursor.parentElement.matches("dialog:modal")'}]),true)
    await control({action:'key',panel:'panel',key:'Escape'})
    assert.equal(await target.executeJavaScript("document.querySelector('dialog').open"),false)
    await assert.rejects(control({action:'click',panel:'missing',x:1,y:1}),/not found/)
    let unexpectedDownloads=0
    target.session.on('will-download',(event,item)=>{
      if (!event.defaultPrevented && !item.getSavePath()) {unexpectedDownloads++;event.preventDefault()}
    })
    const snapshot=await control({action:'snapshot',panel:'panel'})
    const name=snapshot.nodes.find(n=>n.role==='textbox' && n.name==='Name')
    assert.ok(name?.ref,'accessible label must identify the field')
    const again=await control({action:'snapshot',panel:'panel'})
    assert.equal(again.nodes.find(n=>n.role==='textbox' && n.name==='Name').ref,name.ref,'refs must survive repeat snapshots')
    await control({action:'click',panel:'panel',ref:name.ref})
    const dom=await control({action:'snapshot',panel:'panel',format:'dom'})
    assert.ok(dom.nodes.some(n=>n.attributes.id==='choice'))
    await control({action:'click',panel:'panel',selector:'#shadow-button'})
    await assert.rejects(control({action:'click',panel:'panel',selector:'input'}),/multiple/)
    assert.deepEqual(await control({action:'select_option',panel:'panel',selector:'#choice',values:['b']}),{values:['b']})
    assert.deepEqual(await control({action:'check',panel:'panel',selector:'#checked',checked:true}),{checked:true})
    assert.equal(await target.executeJavaScript('document.querySelector("#checked").checked'),true)
    const uploadFile=path.join(directory,'upload.txt');fs.writeFileSync(uploadFile,'synthetic test file')
    await control({action:'upload',panel:'panel',selector:'#upload',files:[uploadFile]})
    assert.equal(await target.executeJavaScript('document.querySelector("#upload").files[0].name'),'upload.txt')
    await control({action:'upload',panel:'panel',selector:'#upload',files:[]})
    assert.equal(await target.executeJavaScript('document.querySelector("#upload").files.length'),0)
    await target.executeJavaScript('setTimeout(()=>{const el=document.createElement("div");el.id="delayed";el.textContent="Ready";document.body.appendChild(el)},150)')
    await control({action:'wait',panel:'panel',selector:'#delayed',timeoutMs:2000})
    await control({action:'wait',panel:'panel',selector:'#missing',state:'detached',timeoutMs:0})
    await assert.rejects(control({action:'wait',panel:'panel',selector:'#missing',timeoutMs:20}),/Timed out/)
    await control({action:'wait',panel:'panel',url:origin+'/',state:'complete',timeoutMs:0})
    const full=await control({action:'screenshot',panel:'panel',fullPage:true})
    assert.ok(full.height>=2200,'full-page capture must include offscreen content')
    const crop=await control({action:'screenshot',panel:'panel',selector:'#bottom'})
    assert.ok(crop.width>10 && crop.height<100,'element capture must crop to element')
    await target.executeJavaScript(`console.error('libro-test-error');Promise.all([fetch('/missing'),fetch('/failed').catch(()=>{})])`)
    const diagnostics=await control({action:'diagnostics',panel:'panel'})
    assert.ok(diagnostics.console.some(e=>e.message.includes('libro-test-error')))
    assert.ok(diagnostics.network.some(e=>e.status===404))
    assert.ok(diagnostics.network.some(e=>e.kind==='failed'))
    await control({action:'diagnostics',panel:'panel',clear:true})
    assert.equal((await control({action:'diagnostics',panel:'panel'})).console.length,0)
    const download=await control({action:'download',panel:'panel',url:origin+'/download',filename:'saved.txt'})
    let downloads
    for(let i=0;i<40;i++) {
      downloads=await control({action:'downloads',panel:'panel'})
      if(downloads.find(d=>d.id===download.id).state==='completed')break
      await delay(25)
    }
    assert.equal(downloads.find(d=>d.id===download.id).state,'completed')
    assert.equal(fs.readFileSync(download.path,'utf8'),'hello')
    const slow=await control({action:'download',panel:'panel',url:origin+'/slow-download'})
    await control({action:'cancel_download',panel:'panel',downloadId:slow.id})
    const stopDownload=await control({action:'download',panel:'panel',url:origin+'/slow-download'})
    const blocked=control({action:'wait',panel:'panel',selector:'#never',timeoutMs:20000})
    const queued=control({action:'text',panel:'panel',text:'must not run'})
    const rejected=Promise.all([assert.rejects(blocked,/cancelled|stopped|paused/),assert.rejects(queued,/paused/)])
    await delay(50)
    await control({action:'stop'})
    await rejected
    assert.deepEqual(await control({action:'status'}),{enabled:true,paused:true})
    await assert.rejects(control({action:'screenshot',panel:'panel'}),/paused/)
    control.setPaused(false)
    for(let i=0;i<40;i++) {
      downloads=await control({action:'downloads',panel:'panel'})
      if(downloads.find(d=>d.id===stopDownload.id).state==='cancelled')break
      await delay(25)
    }
    assert.equal(downloads.find(d=>d.id===stopDownload.id).state,'cancelled')
    control.setEnabled(false)
    assert.equal(target.debugger.isAttached(),false,'disabled control must detach diagnostics')
    await assert.rejects(control({action:'list'}),/disabled in Settings/)
    assert.throws(()=>control.setPaused(false),/disabled in Settings/)
    control.setEnabled(true)
    await control({action:'navigate',panel:'panel',url:origin+'/?next'})
    await control({action:'wait',panel:'panel',state:'complete'})
    await assert.rejects(control({action:'click',panel:'panel',ref:name.ref}),/Stale/)
    assert.equal(unexpectedDownloads,0,'all agent downloads must have a save path before Electron can show a dialog')
    console.log('PASS: native input, snapshots/refs, shadow DOM, selects, checkboxes, upload, waits, screenshots, diagnostics, downloads, stop and stale refs')
  } finally {win.destroy();server.closeAllConnections();server.close();fs.rmSync(directory,{recursive:true,force:true});app.quit()}
}).catch(error=>{console.error(error);app.exit(1)})
